-- Atrapa środowiska Supabase + stan bazy po migracjach 2026-10 … 2026-11f (skrócony)
create role anon nologin;
create role authenticated nologin;
create schema auth;
create schema storage;
grant usage on schema auth, storage, public to anon, authenticated;

create table auth.users (id uuid primary key, email text, deleted_at timestamptz);
create table auth.mfa_factors (id uuid primary key default gen_random_uuid(), user_id uuid references auth.users, status text);
create function auth.jwt() returns jsonb language sql stable as $$
    select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt() ->> 'sub')::uuid $$;
grant execute on function auth.jwt(), auth.uid() to anon, authenticated;

create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text, name text);
create function storage.foldername(name text) returns text[] language sql immutable as $$ select (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'), 1) - 1] $$;
grant execute on function storage.foldername(text) to authenticated;
alter table storage.objects enable row level security;
grant all on storage.objects to authenticated;

-- Supabase domyślnie daje anon i authenticated pełne uprawnienia do nowych tabel
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;
alter default privileges in schema public grant execute on functions to anon, authenticated;

create table public.imports (id uuid primary key default gen_random_uuid(), user_id uuid, file_name text, imported_at timestamptz default now(),
    rows_total int, rows_added int, rows_duplicate int, rows_error int, newest_month text, bank text, owner_id uuid references auth.users);
create table public.categories (id uuid primary key default gen_random_uuid(), user_id uuid, name text not null, color text, monthly_limit_gr int,
    is_fixed boolean default false, sort_order int, created_at timestamptz default now(), is_saving boolean default false, owner_id uuid references auth.users,
    unique nulls not distinct (owner_id, name));
create table public.goals (id bigint generated by default as identity primary key, user_id uuid, name text, keyword text, keywords_out text,
    target_gr int, deadline date, archived boolean default false, created_at timestamptz default now(), opening_balance_gr int, color text, note text,
    interest_rate numeric, interest_threshold_gr int, owner_id uuid references auth.users);
create table public.rules (id bigint generated by default as identity primary key, user_id uuid, phrase text, category text,
    created_at timestamptz default now(), owner_id uuid references auth.users);
create table public.transakcje (id bigint generated by default as identity primary key, user_id uuid, booked_on date, counterparty text, title text,
    account_number text, amount_gr int, category_manual text, splits jsonb, dedup_key text, created_at timestamptz default now(),
    import_id uuid references public.imports on delete set null, note text, receipt_path text, owner_id uuid references auth.users,
    unique nulls not distinct (owner_id, dedup_key));
