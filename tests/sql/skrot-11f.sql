-- Skrót migracji 2026-11f (to, od czego zależy 11g)
create table if not exists public.budzet_czlonkowie (
    user_id uuid primary key references auth.users on delete cascade,
    dodal uuid references auth.users on delete set null,
    dodano timestamptz not null default now());
alter table public.budzet_czlonkowie enable row level security;
revoke all on table public.budzet_czlonkowie from anon, authenticated;
create table if not exists public.ustawienia_budzetu (
    id bigint generated by default as identity primary key,
    owner_id uuid references auth.users on delete cascade,
    konto_wyplat text, zmieniono timestamptz not null default now(),
    constraint ustawienia_budzetu_jeden_na_budzet unique nulls not distinct (owner_id));
revoke all on table public.ustawienia_budzetu from anon;
grant select, insert, update, delete on table public.ustawienia_budzetu to authenticated;

create or replace function public.uzytkownik_budzetu() returns uuid language sql stable set search_path = '' as $$
    select case when coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) then null else auth.uid() end $$;
create or replace function public.czy_czlonek_budzetu() returns boolean language sql stable security definer set search_path = '' as $$
    select exists (select 1 from public.budzet_czlonkowie where user_id = public.uzytkownik_budzetu()) $$;
create or replace function public.budzet_wspolny_stan() returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare v_ja uuid := public.uzytkownik_budzetu();
begin
    if v_ja is null then raise exception 'Wymaga zalogowania' using errcode = '28000'; end if;
    return jsonb_build_object('czlonek', exists (select 1 from public.budzet_czlonkowie where user_id = v_ja));
end; $$;
revoke all on function public.uzytkownik_budzetu() from public, anon;
revoke all on function public.czy_czlonek_budzetu() from public, anon;
revoke all on function public.budzet_wspolny_stan() from public, anon;
grant execute on function public.uzytkownik_budzetu(), public.czy_czlonek_budzetu(), public.budzet_wspolny_stan() to authenticated;

do $$
declare t text; p record;
begin
    foreach t in array array['transakcje', 'rules', 'goals', 'categories', 'imports', 'ustawienia_budzetu'] loop
        execute format('alter table public.%I enable row level security', t);
        for p in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
            execute format('drop policy %I on public.%I', p.policyname, t);
        end loop;
        execute format($f$
            create policy budzet_dostep on public.%I for all to authenticated
                using ((owner_id is null and (select public.czy_czlonek_budzetu())) or owner_id = (select public.uzytkownik_budzetu()))
                with check ((owner_id is null and (select public.czy_czlonek_budzetu())) or owner_id = (select public.uzytkownik_budzetu()))$f$, t);
    end loop;
end $$;

drop policy if exists paragony_dostep on storage.objects;
create policy paragony_dostep on storage.objects for all to authenticated
    using (bucket_id = 'paragony' and (((storage.foldername(name))[1] = 'wspolny' and (select public.czy_czlonek_budzetu()))
             or (storage.foldername(name))[1] = (select public.uzytkownik_budzetu())::text));

